    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
                try {
            Empleado e = new Empleado();
            e.setNombre(txtNombre.getText().trim());
            e.setPuesto(txtPuesto.getText().trim());
            e.setDepartamento(txtDepartamento.getText().trim());
            e.setSalario(txtSalario.getText().trim());
            e.setFechaContratacion(txtFecha.getText().trim());

            if (empleadoSeleccionado == null) {
                api.crear(e);          // modo nuevo -> POST
            } else {
                e.setId(empleadoSeleccionado.getId());
                api.editar(e);         // modo edición -> PUT
            }
            cargarEmpleados();
        } catch (Exception ex) {
            mostrarError(ex);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
                if (empleadoSeleccionado == null) {
            JOptionPane.showMessageDialog(this, "Selecciona un empleado de la tabla");
            return;
        }
        int resp = JOptionPane.showConfirmDialog(this,
                "¿Eliminar a " + empleadoSeleccionado.getNombre() + "?",
                "Confirmar", JOptionPane.YES_NO_OPTION);
        if (resp == JOptionPane.YES_OPTION) {
            try {
                api.eliminar(empleadoSeleccionado.getId());
                cargarEmpleados();
            } catch (Exception ex) {
                mostrarError(ex);
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

