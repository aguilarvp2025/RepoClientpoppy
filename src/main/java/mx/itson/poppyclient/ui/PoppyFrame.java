        private void configurarTabla() {
        modelo = new DefaultTableModel(
                new Object[]{"ID", "Nombre", "Puesto", "Departamento", "Salario", "Fecha"}, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false; // la tabla es solo lectura; se edita desde el formulario
            }
        };
        tablaEmpleados.setModel(modelo);
        tablaEmpleados.setSelectionMode(javax.swing.ListSelectionModel.SINGLE_SELECTION);
        tablaEmpleados.getSelectionModel().addListSelectionListener((ListSelectionEvent ev) -> {
            if (!ev.getValueIsAdjusting()) {
                seleccionarFila();
            }
        });
    }

    private void cargarEmpleados() {
        try {
            empleados = api.listar();
            modelo.setRowCount(0);
            for (Empleado e : empleados) {
                modelo.addRow(new Object[]{
                    e.getId(), e.getNombre(), e.getPuesto(),
                    e.getDepartamento(), e.getSalario(), e.getFechaContratacion()
                });
            }
            limpiarFormulario();
        } catch (Exception ex) {
            mostrarError(ex);
        }
    }

    private void seleccionarFila() {
        int fila = tablaEmpleados.getSelectedRow();
        if (fila < 0) {
            return;
        }
        empleadoSeleccionado = empleados.get(fila);
        txtNombre.setText(empleadoSeleccionado.getNombre());
        txtPuesto.setText(empleadoSeleccionado.getPuesto());
        txtDepartamento.setText(empleadoSeleccionado.getDepartamento());
        txtSalario.setText(empleadoSeleccionado.getSalario());
        txtFecha.setText(empleadoSeleccionado.getFechaContratacion());
    }

    private void limpiarFormulario() {
        empleadoSeleccionado = null;
        txtNombre.setText("");
        txtPuesto.setText("");
        txtDepartamento.setText("");
        txtSalario.setText("");
        txtFecha.setText("");
        tablaEmpleados.clearSelection();
    }

    private void mostrarError(Exception ex) {
        JOptionPane.showMessageDialog(this, ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
    }
